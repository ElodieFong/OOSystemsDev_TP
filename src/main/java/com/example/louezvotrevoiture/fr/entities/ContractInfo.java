package com.example.louezvotrevoiture.fr.entities;

public class ContractInfo {
    private String begin;
    private String end;

    public ContractInfo() {
    }

    public String getBegin() {
        return begin;
    }

    public void setBegin(String begin) {
        this.begin = begin;
    }

    public String getEnd() {
        return end;
    }

    public void setEnd(String end) {
        this.end = end;
    }
}